#[allow(dead_code)]
#[derive(TS)]
struct HistoryArgs {
    #[ts(type = "unknown", optional)]
    _filter: Option<serde_json::Value>,
    #[ts(optional)]
    _cursor: Option<String>,
}

// Tauri transports serde_json numbers, including u64/i64. ts-rs's default
// bigint representation describes other transports; adapt declarations here.
fn json_numbers(source: String) -> String {
    source.replace("bigint", "number")
}
fn declaration<T: TS>() -> String {
    format!("export {}\n", json_numbers(T::decl()))
}
fn entry<A: TS, R: TS>(name: &str) -> String {
    format!(
        "  {name}: [{}, {}];\n",
        json_numbers(A::inline()),
        json_numbers(R::name())
    )
}

