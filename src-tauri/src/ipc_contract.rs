macro_rules! args {
    ($name:ident { $($field:ident: $kind:ty),* $(,)? }) => {
        #[allow(dead_code)]
        #[derive(TS)]
        #[ts(rename_all = "camelCase")]
        struct $name { $($field: $kind),* }
    };
}
