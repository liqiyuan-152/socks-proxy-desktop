#[test]
fn generate_ipc_contract() {
    let public = public_contract();
    let handler = include_str!("lib.rs")
        .split("tauri::generate_handler![")
        .nth(1)
        .unwrap()
        .split("])")
        .next()
        .unwrap();
    for line in handler
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty())
    {
        let name = line.trim_end_matches(',').rsplit("::").next().unwrap();
        assert!(
            public.contains(&format!("  {name}:")),
            "registered command missing: {name}"
        );
    }
    for internal in [
        "credential_ref",
        "ProxyCredential",
        "PersistedConfiguration",
        "LatencyInput",
        "password:",
    ] {
        assert!(
            !public.contains(internal),
            "internal boundary leaked: {internal}"
        );
    }
    let mut secret = String::from("// Generated explicit credential IPC boundary. Do not edit or log values.\nimport type { ProxyProtocol } from './ipc';\n");
    secret.push_str(&declaration::<CredentialUpdate>());
    secret.push_str(&declaration::<ProfileInput>());
    secret.push_str(&declaration::<ProfileCredentialView>());
    if let Some(directory) = std::env::var_os("SOCKS_PROXY_CONTRACT_OUTPUT") {
        let directory = std::path::PathBuf::from(directory);
        std::fs::create_dir_all(&directory).unwrap();
        std::fs::write(directory.join("ipc.ts"), public).unwrap();
        std::fs::write(directory.join("credentials.ts"), secret).unwrap();
    }
}

#[test]
fn public_wire_values_match_generated_enums_numbers_and_error_shape() {
    let prediction = RouteTestResult {
        target: "example.com".into(),
        port: 443,
        configuration_revision: 7,
        stage: RouteStage::UserRule,
        action: RuleAction::Direct,
        proxy_profile_id: None,
        proxy_name: None,
        matched_rule_id: Some("first".into()),
        matched_rule_name: Some("First".into()),
        reason: "首条用户规则".into(),
        data_date: None,
    };
    let value = serde_json::to_value(prediction).unwrap();
    assert_eq!(value["stage"], "user_rule");
    assert_eq!(value["configuration_revision"], 7);
    assert_eq!(value["port"], 443);
    assert!(value["proxy_profile_id"].is_null());
    let stage = RouteStage::decl();
    for name in [
        "user_rule",
        "china_domain",
        "private_ip",
        "china_ip",
        "final",
    ] {
        assert!(stage.contains(name));
    }
    for state in [
        LatencyTaskState::Queued,
        LatencyTaskState::Running,
        LatencyTaskState::Cancelling,
        LatencyTaskState::Cancelled,
        LatencyTaskState::Succeeded,
        LatencyTaskState::Failed,
    ] {
        let wire = serde_json::to_value(state).unwrap();
        assert!(LatencyTaskState::decl().contains(wire.as_str().unwrap()));
    }
    let error = serde_json::to_value(AppError::unavailable("测试不可用")).unwrap();
    assert_eq!(error["code"], "unavailable");
    assert_eq!(error["message"], "测试不可用");
    assert_eq!(error["fields"], serde_json::json!([]));
    // Only this explicit DTO carries plaintext credentials over the command boundary.
    let credential = serde_json::to_value(ProfileCredentialView {
        username: "synthetic-user".into(),
        password: "synthetic-secret".into(),
    })
    .unwrap();
    assert_eq!(credential.as_object().unwrap().len(), 2);
    assert!(!public_contract().contains("synthetic-secret"));
}

#[test]
fn runtime_mode_parameters_match_wire_and_generated_contract() {
    for use_china_direct in [false, true] {
        for default_action in [RuleAction::Proxy, RuleAction::Direct] {
            let mode = RuntimeMode::Rules {
                use_china_direct,
                default_action,
            };
            let wire = serde_json::json!({"rules": {
                "use_china_direct": use_china_direct,
                "default_action": default_action,
            }});
            assert_eq!(serde_json::to_value(mode).unwrap(), wire);
            assert_eq!(serde_json::from_value::<RuntimeMode>(wire).unwrap(), mode);
        }
    }
    for (mode, wire) in [
        (RuntimeMode::Global, "global"),
        (RuntimeMode::Direct, "direct"),
    ] {
        assert_eq!(serde_json::to_value(mode).unwrap(), wire);
        assert_eq!(
            serde_json::from_value::<RuntimeMode>(wire.into()).unwrap(),
            mode
        );
    }
    for invalid in [
        serde_json::json!("rules"),
        serde_json::json!({"rules": {"use_china_direct": false}}),
        serde_json::json!({"rules": {"use_china_direct": false, "default_action": "reject"}}),
    ] {
        assert!(serde_json::from_value::<RuntimeMode>(invalid).is_err());
    }
    let declaration = RuntimeMode::decl();
    assert!(declaration.contains("use_china_direct: boolean"));
    assert!(declaration.contains("default_action: RuleAction"));
    assert!(public_contract().contains(&format!("export {declaration}")));
}
